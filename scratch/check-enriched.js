function parseProductName(raw, index) {
  let cleaned = raw.trim();
  cleaned = cleaned.replace(/\s+GLS\s*$/i, '');
  
  let mainName = cleaned;
  const splitters = [
    " капс.", " капс", " порошок", " шипучие", " детс.", " для детей", " паст.", " таб.", " таб"
  ];
  for (const s of splitters) {
    if (cleaned.toLowerCase().includes(s)) {
      mainName = cleaned.split(new RegExp(s, "i"))[0].trim();
      break;
    }
  }
  
  mainName = mainName.replace(/\s+\d+мг\s*$/i, '').trim();
  mainName = mainName.replace(/\s+\d+МЕ\s*$/i, '').trim();
  mainName = mainName.replace(/\s+\d+мкг\s*$/i, '').trim();
  
  return mainName.toLowerCase();
}

const targetSet = new Set(RAW_PRODUCTS.map((p, idx) => parseProductName(p, idx)));

const enrichedKeys = Object.keys(enriched);
console.log('Enriched keys in enriched_gls_products.json:', enrichedKeys.length);

const extraKeys = [];
for (const key of enrichedKeys) {
  const normKey = key.toLowerCase();
  // check if key or key name matches one in our targetSet
  let found = false;
  if (targetSet.has(normKey)) {
    found = true;
  } else {
    // try matching names
    const enrichedName = enriched[key].name || '';
    if (targetSet.has(enrichedName.toLowerCase())) {
      found = true;
    }
  }
  
  if (!found) {
    extraKeys.push(key);
  }
}

