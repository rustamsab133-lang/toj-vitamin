/**
 * Умный поиск обогащенных свойств товара из базы знаний RAG
 */
export function findEnrichmentForProduct(pName: string, enrichedData: Record<string, any>): any {
  if (!pName || !enrichedData) return null;
  const name = pName.toLowerCase().trim();

  // 1. Проверяем точные синонимы и алиасы
  for (const [alias, targetKey] of Object.entries(ENRICHMENT_ALIASES)) {
    if (name.includes(alias)) {
      if (enrichedData[targetKey]?.properties?.length) {
        return enrichedData[targetKey];
      }
    }
  }

  // 2. Прямое совпадение по ключу (если в нем есть реальные свойства)
  if (enrichedData[name]?.properties?.length) {
    return enrichedData[name];
  }

  // 3. Нормализованный поиск без знаков препинания и дозировок
  const normalize = (str: string) => str.replace(/[\(\)\d№мгг\-\+\s_%—]/g, '');
  const nameNorm = normalize(name);

  for (const [key, val] of Object.entries(enrichedData)) {
    if (val?.properties?.length && normalize(key) === nameNorm) {
      return val;
    }
  }

  // 4. Очищенный поиск по значимой части названия (с сохранением корней)
  const cleaned = name
    .replace(/\([^)]+\)/g, ' ')
    .replace(/капс\.*|таб\.*|порошок|экстракт|сироп/gi, ' ')
    .replace(/gls|pharm|№\d+|\d+\s*мг|\d+\s*г|\d+\s*ие|\d+\s*ме/gi, ' ')
    .replace(/[\-\–\—]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

  if (enrichedData[cleaned]?.properties?.length) {
    return enrichedData[cleaned];
  }

  for (const [key, val] of Object.entries(enrichedData)) {
    if (!val?.properties?.length) continue;
    const keyCleaned = key.replace(/[\-\–\—]/g, ' ').replace(/\s+/g, ' ').trim();
    if (cleaned.length > 2 && (cleaned.includes(keyCleaned) || keyCleaned.includes(cleaned))) {
      return val;
    }
  }

  return enrichedData[name] || null;
}

/**
 * Формирует полноценное, богатое фактами и безопасное описание для товара
 */
export function getProductDescription(
  product: { name: string; description?: string }, 
  enrichedData: Record<string, any>
): string {
  const safeTitle = sanitizeTitle(product.name);
  const enrichment = findEnrichmentForProduct(product.name, enrichedData);

  let rawText = '';
  if (enrichment?.properties && Array.isArray(enrichment.properties) && enrichment.properties.length > 0) {
    rawText = enrichment.properties.join('. ');
  } else if (
    product.description && 
    !product.description.includes('Премиальный продукт GLS') && 
    !product.description.includes('Купить') && 
    product.description.length > 30
  ) {
    rawText = product.description;
  }

  return sanitizeDescription(rawText, safeTitle);
}

