// Обязательный дисклеймер Meta для пищевых добавок (White-hat compliance)
export const MANDATORY_SUPPLEMENT_DISCLAIMER = 
  'Биологически активная добавка к пище (БАД). Не является лекарственным средством.';

/**
 * Очищает название товара для Meta Catalog
 */
export function sanitizeTitle(rawTitle: string): string {
  if (!rawTitle) return '';
  const trimmed = rawTitle.trim();

  // 1. Проверяем точный оверрайд
  if (EXACT_TITLE_OVERRIDES[trimmed]) {
    return EXACT_TITLE_OVERRIDES[trimmed];
  }

  // 2. Обрабатываем скобки с маркетинговыми словами
  let clean = trimmed;
  for (const [pattern, replacement] of PARENTHESIS_REPLACEMENTS) {
    clean = clean.replace(pattern, replacement);
  }

  // 3. Убираем спамные знаки и множественные пробелы
  clean = clean
    .replace(/[!*?]+/g, '')
    .replace(/\s+/g, ' ')
    .trim();

  // 4. Защита от ALL CAPS (за исключением коротких аббревиатур типа GLS, MSM, B5)
  if (clean === clean.toUpperCase() && clean.length > 5) {
    clean = clean.charAt(0) + clean.slice(1).toLowerCase();
  }

  return clean;
}

/**
 * Очищает и делает безопасным описание товара для Meta Catalog
 */
export function sanitizeDescription(rawDescription: string, productName: string): string {
  let text = (rawDescription || '').trim();

  // Если описания нет или оно слишком банальное/пустое — генерируем нейтральное безопасное
  if (!text || text.length < 20) {
    text = `Высококачественный комплекс ${productName} от бренда GLS Pharmaceuticals. Предназначен для ежедневной поддержки жизненного тонуса, энергии и отличного самочувствия. Произведено по строгим стандартам качества.`;
  }

  // Применяем все правила антибан-санитайзера
  for (const [pattern, replacement] of DESCRIPTION_REPLACEMENTS) {
    text = text.replace(pattern, replacement);
  }

  // Удаляем множественные точки, пробелы и артефакты склейки
  text = text
    .replace(/\s+/g, ' ')
    .replace(/\.{2,}/g, '.')
    .replace(/\s+\./g, '.')
    .trim();

  // Гарантируем, что в конце есть обязательный дисклеймер
  if (!text.includes('Не является лекарственным средством')) {
    text = `${text} ${MANDATORY_SUPPLEMENT_DISCLAIMER}`;
  }

  // Ограничение длины Meta (до 5000 символов, рекомендуем до 1000)
  if (text.length > 4900) {
    text = text.substring(0, 4800) + '... ' + MANDATORY_SUPPLEMENT_DISCLAIMER;
  }

  return text;
}

/**
 * Валидатор безопасности: проверяет, нет ли в тексте опасных стоп-слов Meta
 */
export const FORBIDDEN_META_WORDS_REGEX = /(похудени|жиросжиган|сжиг.*жир|излечив|исцеля|диабет|тестостерон|потенци(?!ал)|эрекц|либидо|онкол|(?<![а-яА-ЯёЁ])рак(?![а-яА-ЯёЁ])|воспален|мышечные\s*боли|устраняет\s*бол|детокс|шлак|гармон|гормон|метформин)/i;

export interface SafetyCheckResult {
  isSafe: boolean;
  violations: string[];
}

export function checkMetaSafety(text: string): SafetyCheckResult {
  const violations: string[] = [];
  
  // Исключаем разрешенный дисклеймер из проверки стоп-слова
  const textWithoutDisclaimer = text.replace(MANDATORY_SUPPLEMENT_DISCLAIMER, '');

  if (FORBIDDEN_META_WORDS_REGEX.test(textWithoutDisclaimer)) {
    const match = textWithoutDisclaimer.match(FORBIDDEN_META_WORDS_REGEX);
    if (match) {
      violations.push(`Найдено рискованное слово/фрагмент: "${match[0]}"`);
    }
  }

  return {
    isSafe: violations.length === 0,
    violations
  };
}

/**
 * Экранирование значений для CSV по стандарту RFC 4180
 */
export function escapeCsvField(val: string | number | null | undefined): string {
  if (val === null || val === undefined) return '""';
  const str = String(val).replace(/"/g, '""');
  return `"${str}"`;
}

